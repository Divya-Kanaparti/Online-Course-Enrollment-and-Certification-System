-- Purpose: Shows the number of enrollments for every course, including courses with no enrollments.
-- Output: Execute this SELECT statement in MySQL to view the actual report rows.
-- R1. Number of students enrolled in each course
SELECT c.course_name, COUNT(e.enrollment_id) AS total_enrollments
FROM courses c
LEFT JOIN batches b ON c.course_id = b.course_id
LEFT JOIN enrollments e ON b.batch_id = e.batch_id
GROUP BY c.course_name
ORDER BY total_enrollments DESC;

-- Purpose: Calculates the total amount of fees paid by students for each course.
-- Output: Execute this SELECT statement in MySQL to view the actual report rows.
-- R2. Total fees collected for each course
SELECT c.course_name, COALESCE(SUM(e.fee_paid), 0) AS fees_collected
FROM courses c
LEFT JOIN batches b ON c.course_id = b.course_id
LEFT JOIN enrollments e ON b.batch_id = e.batch_id
GROUP BY c.course_name;

-- Purpose: Counts the enrollments in each batch.
-- Output: Execute this SELECT statement in MySQL to view the actual report rows.
-- R3. Batch-wise active student count

SELECT
    b.batch_code,
    c.course_name,
    b.max_seats,

    COUNT(
        CASE
            WHEN e.enrollment_status <> 'Dropped'
            THEN e.enrollment_id
        END
    ) AS student_count,

    b.max_seats -
    COUNT(
        CASE
            WHEN e.enrollment_status <> 'Dropped'
            THEN e.enrollment_id
        END
    ) AS available_seats

FROM batches b

JOIN courses c
    ON c.course_id = b.course_id

LEFT JOIN enrollments e
    ON e.batch_id = b.batch_id

GROUP BY
    b.batch_id,
    b.batch_code,
    c.course_name,
    b.max_seats

ORDER BY student_count DESC;


-- Purpose: Identifies enrollments where the amount paid is less than the course fee.
-- Output: Execute this SELECT statement in MySQL to view the actual report rows.
-- R4. Students who have not paid the full course fee
SELECT student_name, course_name, batch_code, course_fee,
       fee_paid, balance_due, payment_status
FROM v_enrollment_details
WHERE payment_status <> 'Paid';

-- Purpose: Lists students whose assessment result is Pass.
-- Output: Execute this SELECT statement in MySQL to view the actual report rows.
-- R5. Students who passed each assessment
SELECT s.first_name, s.last_name, a.assessment_name, ar.marks_obtained
FROM assessment_results ar
JOIN enrollments e ON ar.enrollment_id = e.enrollment_id
JOIN students s ON e.student_id = s.student_id
JOIN assessments a ON ar.assessment_id = a.assessment_id
WHERE ar.result_status = 'Pass';

-- Purpose: Lists students whose assessment result is Fail.
-- Output: Execute this SELECT statement in MySQL to view the actual report rows.
-- R6. Students who failed each assessment
SELECT s.first_name, s.last_name, a.assessment_name, ar.marks_obtained
FROM assessment_results ar
JOIN enrollments e ON ar.enrollment_id = e.enrollment_id
JOIN students s ON e.student_id = s.student_id
JOIN assessments a ON ar.assessment_id = a.assessment_id
WHERE ar.result_status = 'Fail';

-- Purpose: Counts how many batches are handled by each trainer.
-- Output: Execute this SELECT statement in MySQL to view the actual report rows.
-- R7. Trainer-wise batch count
SELECT t.trainer_name, COUNT(b.batch_id) AS batches_handled
FROM trainers t
LEFT JOIN batches b ON t.trainer_id = b.trainer_id
GROUP BY t.trainer_name;

-- Purpose: Calculates the average assessment marks for each course.
-- Output: Execute this SELECT statement in MySQL to view the actual report rows.
-- R8. Course-wise average assessment percentage
SELECT c.course_name,
       ROUND(AVG(ar.marks_obtained * 100.0 / a.max_marks), 2) AS average_percentage
FROM courses c
JOIN batches b  ON c.course_id = b.course_id
JOIN assessments a ON b.batch_id = a.batch_id
JOIN assessment_results ar ON a.assessment_id = ar.assessment_id
GROUP BY c.course_name;

-- Purpose: Displays certificate details together with the student, batch and course information.
-- Output: Execute this SELECT statement in MySQL to view the actual report rows.
-- R9. Certificate details report
SELECT cert.certificate_no, s.first_name, s.last_name,
       c.course_name, cert.final_percentage, cert.grade
FROM certificates cert
JOIN enrollments e ON cert.enrollment_id = e.enrollment_id
JOIN students s ON e.student_id = s.student_id
JOIN batches b ON e.batch_id = b.batch_id
JOIN courses c ON b.course_id = c.course_id
ORDER BY cert.certificate_no;


-- R10. Trainer-wise course assignment report

SELECT
    t.trainer_id,
    t.trainer_name,
    t.specialization,
    COUNT(ct.course_id) AS total_courses,

    GROUP_CONCAT(
        c.course_name
        ORDER BY c.course_name
        SEPARATOR ', '
    ) AS assigned_courses

FROM trainers t

LEFT JOIN course_trainers ct
    ON ct.trainer_id = t.trainer_id

LEFT JOIN courses c
    ON c.course_id = ct.course_id

GROUP BY
    t.trainer_id,
    t.trainer_name,
    t.specialization

ORDER BY total_courses DESC;


-- R11. Student enrollment history

SELECT
    s.student_id,
    CONCAT(s.first_name, ' ', s.last_name) AS student_name,
    c.course_name,
    b.batch_code,
    e.enrollment_date,
    e.enrollment_status,
    e.payment_status,
    e.fee_paid,
    c.fee - e.fee_paid AS balance_due

FROM students s

JOIN enrollments e
    ON s.student_id = e.student_id

JOIN batches b
    ON e.batch_id = b.batch_id

JOIN courses c
    ON b.course_id = c.course_id

ORDER BY
    s.student_id,
    e.enrollment_date DESC;

-- R12. Certificate eligibility report
SELECT student_name, course_name, batch_code,
       final_percentage, payment_status, eligibility, certificate_issued
FROM v_certificate_eligibility
ORDER BY course_name, batch_code, student_name;

-- R13. Student performance report
SELECT student_name, course_name, batch_code,
       completed_assessments, total_assessments,
       progress_percentage, marks_percentage, failed_assessments
FROM v_student_progress
ORDER BY marks_percentage DESC;